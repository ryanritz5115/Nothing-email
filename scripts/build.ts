import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  PLATFORMS,
  ROOT,
  createEngine,
  flatten,
  listFixtures,
  listTemplates,
  renderTemplate,
  templatePath,
} from './lib.ts';

/* Writes one paste-ready file per template into dist/, with every       */
/* {% include %} inlined, then renders each template against every       */
/* fixture for its platform so broken branches fail the build.            */

const engine = createEngine();
const distDir = join(ROOT, 'dist');
rmSync(distDir, { recursive: true, force: true });

let built = 0;
let checks = 0;
const failures: string[] = [];

for (const platform of PLATFORMS) {
  const templates = listTemplates(platform);
  if (templates.length === 0) continue;

  const outDir = join(distDir, platform);
  mkdirSync(outDir, { recursive: true });
  const fixtures = listFixtures(platform);

  for (const name of templates) {
    const source = `${platform}/${name}.liquid`;

    let flat: string;
    try {
      flat = flatten(templatePath(platform, name));
      engine.parse(flat);
    } catch (error) {
      failures.push(`${source}: ${(error as Error).message}`);
      continue;
    }

    const header = `{%- comment -%} GENERATED by npm run build from ${source}. Edit the source, not this file. {%- endcomment -%}\n`;
    writeFileSync(join(outDir, `${name}.liquid`), header + flat);
    built++;

    for (const fixture of fixtures) {
      checks++;
      try {
        const html = await renderTemplate(engine, platform, name, fixture.name);
        if (/Liquid (syntax )?error/i.test(html)) {
          failures.push(`${source} × ${fixture.name}: rendered output contains a Liquid error`);
        }
      } catch (error) {
        failures.push(`${source} × ${fixture.name}: ${(error as Error).message}`);
      }
    }
  }
}

console.log(`\n  Built ${built} template(s) into dist/, ran ${checks} fixture render check(s).`);

if (failures.length) {
  console.error(`\n  ${failures.length} failure(s):\n`);
  for (const f of failures) console.error(`  ✗ ${f}`);
  console.error('');
  process.exit(1);
}

console.log('  All renders passed.\n');
