import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  PLATFORMS,
  ROOT,
  createEngine,
  flatten,
  listFixtures,
  listTemplates,
  renderTemplate,
  templateExtension,
  templatePath,
} from './lib.ts';
import { validateRecharge } from './recharge.ts';

/* Writes one paste-ready file per template into dist/, with every       */
/* {% include %} inlined, then renders each template against every       */
/* fixture in its own fixtures folder so broken branches fail the build. */

const engine = createEngine();
const distDir = join(ROOT, 'dist');
rmSync(distDir, { recursive: true, force: true });

let built = 0;
let checks = 0;
const failures: string[] = [];

for (const platform of PLATFORMS) {
  const templates = listTemplates(platform);
  if (templates.length === 0) continue;

  const outDir = join(distDir, platform);
  mkdirSync(outDir, { recursive: true });

  for (const name of templates) {
    const source = `${platform}/${name}${templateExtension(platform)}`;
    const fixtures = listFixtures(platform, name);

    let flat: string;
    try {
      flat = flatten(templatePath(platform, name));
      if (platform === 'recharge') await validateRecharge(flat);
      else engine.parse(flat);
    } catch (error) {
      failures.push(`${source}: ${(error as Error).message}`);
      continue;
    }

    if (fixtures.length === 0) {
      failures.push(`${source}: no fixtures in fixtures/${platform}/${name}/`);
    }

    const header = platform === 'recharge'
      ? `{# GENERATED by npm run build from ${source}. Edit the source, not this file. #}\n`
      : `{%- comment -%} GENERATED by npm run build from ${source}. Edit the source, not this file. {%- endcomment -%}\n`;
    writeFileSync(join(outDir, `${name}${platform === 'recharge' ? '.html' : '.liquid'}`), header + flat);
    built++;

    for (const fixture of fixtures) {
      checks++;
      try {
        const html = await renderTemplate(engine, platform, name, fixture.name);
        if (/Liquid (syntax )?error|(?:TemplateSyntax|Undefined)Error:/i.test(html)) {
          failures.push(`${source} × ${fixture.name}: rendered output contains a template error`);
        }
      } catch (error) {
        failures.push(`${source} × ${fixture.name}: ${(error as Error).message}`);
      }
    }
  }
}

console.log(`\n  Built ${built} template(s) into dist/, ran ${checks} fixture render check(s).`);

if (failures.length) {
  console.error(`\n  ${failures.length} failure(s):\n`);
  for (const f of failures) console.error(`  ✗ ${f}`);
  console.error('');
  process.exit(1);
}

console.log('  All renders passed.\n');
